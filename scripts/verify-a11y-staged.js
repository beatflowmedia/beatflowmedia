#!/usr/bin/env node
//
// scripts/verify-a11y-staged.js
//
//   npm run verify:a11y                    # the staged files
//   npm run verify:a11y -- --all           # every file under src/
//   npm run verify:a11y -- --write         # regenerate the baseline below
//   npm run verify:a11y -- --files a,b,c   # specific files
//
// ACCESSIBILITY AS A RATCHET, NOT A WALL.
//
// WHY THIS EXISTS
// The pre-commit hook ran `agents/cli.js uiux review --exit-on-critical` over the
// STAGED FILES WHOLE, and the hook's own comment explains what it was trying to achieve:
//
//     "New code is held to the line; existing debt is a ratchet to work down,
//      recorded in CLAUDE.md, not a wall across every commit."
//
// That is the right policy and it is not what the code did. Judging a whole file means a
// one-line change to a legacy file imports every pre-existing issue in it. Moving one
// JSON-LD tag in Playlist.js on 2026-10-23 presented 23 accessibility findings for review
// -- not one of them in the changed line, and not one of them introduced that day. The
// new file in the same commit had zero.
//
// A gate that fails on debt you did not create has exactly one outcome, and the hook says
// so itself: `--no-verify` becomes the normal way to commit. It had already happened once
// in this repository, which is why that warning is in the hook.
//
// SO THE SHAPE IS THE ONE USED TWICE ALREADY HERE -- KNOWN_FIXTURES in
// verify-no-fixtures.js and KNOWN_UNRESOLVED in verify-deps.js. Record the baseline in
// code, reviewable in a pull request, and fail only on GROWTH:
//
//     a file not in the baseline    ->  any issue fails
//     a file in the baseline        ->  more than its recorded count fails
//     a file below its baseline     ->  reported as CLEARED, so the number comes down
//
// WHAT IT DOES NOT DO. It does not gate on the design-token or music-UX findings the
// uiux review also reports. Those stay a report. Accessibility is the one the global
// standard calls a floor that is "never traded" for style, so it is the one with a gate.
//
// THE NUMBER IS CHECKED, NOT TRUSTED. `--all` prints the total next to the sum of the
// baseline, because a reconciler reporting a number needs its number checked too -- six
// instruments read low in the five days before this was written.

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const AccessibilityChecker = require('../agents/core/AccessibilityChecker');

const ROOT = path.resolve(__dirname, '..');
const SELF = path.join(__dirname, 'verify-a11y-staged.js');

// Only CRITICAL and HIGH gate. MEDIUM and LOW are reported by the uiux review and are
// not worth blocking a commit over -- a gate that catches everything catches nothing,
// because it gets turned off.
const GATING = new Set(['CRITICAL', 'HIGH']);

/**
 * THE BASELINE: accessibility issues per file, as of 2026-10-23.
 *
 * 124 files, 464 gating issues. Generated by `--write`, never edited by hand upward.
 * A number here is a debt, not a permission: the only correct direction is down, and
 * `--write` after clearing some is how it tightens.
 */
const BASELINE = require('./a11y-baseline.json');

const rel = (f) => path.relative(ROOT, path.resolve(f)).split(path.sep).join('/');

function sourceFiles(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(full, out);
    else if (/\.(js|jsx)$/.test(entry.name) && !/\.test\.(js|jsx)$/.test(entry.name)) out.push(full);
  }
  return out;
}

function stagedFiles() {
  const out = execSync('git diff --cached --name-only --diff-filter=ACM', { cwd: ROOT })
    .toString().split('\n').map((s) => s.trim()).filter(Boolean)
    .filter((f) => /\.(js|jsx)$/.test(f) && !/\.test\.(js|jsx)$/.test(f));
  return out.filter((f) => fs.existsSync(path.join(ROOT, f)));
}

(async () => {
  const argv = process.argv.slice(2);
  const flag = (n) => argv.includes(n);
  const valueOf = (n) => {
    const i = argv.indexOf(n);
    return i >= 0 ? argv[i + 1] : null;
  };

  const checker = new AccessibilityChecker();

  let files;
  if (flag('--all') || flag('--write')) files = sourceFiles(path.join(ROOT, 'src')).map(rel);
  else if (valueOf('--files')) files = valueOf('--files').split(',').map((s) => s.trim()).filter(Boolean);
  else files = stagedFiles();

  if (!files.length) {
    console.log('\nverify:a11y — no JavaScript files to check.\n');
    process.exit(0);
  }

  console.log('\nverify:a11y — accessibility, ratcheted against a recorded baseline\n');
  console.log('  files checked: ' + files.length + (flag('--all') || flag('--write') ? '  (all of src/)' : '  (staged)'));

  const counts = {};
  const detail = {};
  let threw = 0;

  for (const f of files) {
    let issues;
    try {
      issues = await checker.validateFile(path.join(ROOT, f));
    } catch (err) {
      // A checker that throws and a checker that finds nothing look identical from the
      // outside. validateHeadingHierarchy threw a ReferenceError on every heading-level
      // skip until 2026-10-23, so HEADING_HIERARCHY_SKIP had never once been reported.
      threw += 1;
      console.error('  THREW  ' + f + '  ' + err.message);
      continue;
    }
    const gating = issues.filter((i) => GATING.has(i.severity));
    if (gating.length) {
      counts[f] = gating.length;
      detail[f] = gating;
    }
  }

  if (threw) {
    console.error('\n  ' + threw + ' file(s) crashed the checker. That is a checker bug, not a clean pass.\n');
    process.exit(1);
  }

  // --- regenerate -------------------------------------------------------------
  if (flag('--write')) {
    const sorted = Object.keys(counts).sort().reduce((o, k) => { o[k] = counts[k]; return o; }, {});
    const total = Object.values(sorted).reduce((a, b) => a + b, 0);
    fs.writeFileSync(
      path.join(__dirname, 'a11y-baseline.json'),
      JSON.stringify(sorted, null, 2) + '\n',
      'utf8'
    );
    console.log('  wrote scripts/a11y-baseline.json — ' + Object.keys(sorted).length +
      ' files, ' + total + ' gating issues');
    console.log('  (update the count in the BASELINE comment in ' + rel(SELF) + ')\n');
    process.exit(0);
  }

  // --- compare ----------------------------------------------------------------
  const grown = [];
  const appeared = [];
  const cleared = [];

  for (const f of files) {
    const now = counts[f] || 0;
    const was = BASELINE[f];
    if (was === undefined) {
      if (now > 0) appeared.push({ f, now });
    } else if (now > was) {
      grown.push({ f, was, now });
    } else if (now < was) {
      cleared.push({ f, was, now });
    }
  }

  if (flag('--all')) {
    const now = Object.values(counts).reduce((a, b) => a + b, 0);
    const was = Object.values(BASELINE).reduce((a, b) => a + b, 0);
    console.log('  gating issues: ' + now + '   baseline sum: ' + was +
      (now === was ? '   (agree)' : '   <- CHECK THIS'));
  }

  console.log('');

  if (cleared.length) {
    console.log('  CLEARED — re-run with -- --write so the ratchet tightens:');
    cleared.forEach(({ f, was, now }) => console.log('     ' + f + '  ' + was + ' -> ' + now));
    console.log('');
  }

  if (!appeared.length && !grown.length) {
    console.log('  No file gained an accessibility issue.\n');
    process.exit(0);
  }

  for (const { f, now } of appeared) {
    console.log('  NEW FILE WITH ISSUES: ' + f + '  (' + now + ')');
    detail[f].forEach((i) => console.log('     [' + i.severity + '] ' + i.type +
      '  line ' + (i.line || '?') + '  ' + (i.message || '')));
  }
  for (const { f, was, now } of grown) {
    console.log('  GREW: ' + f + '  ' + was + ' -> ' + now);
    detail[f].forEach((i) => console.log('     [' + i.severity + '] ' + i.type +
      '  line ' + (i.line || '?') + '  ' + (i.message || '')));
  }

  console.log('');
  console.log('  Fix these, or if a finding is wrong, fix the DETECTOR and prove it both');
  console.log('  ways — it fires on a real fault and stays quiet on the false one. Three');
  console.log('  rules in this checker have matched prose rather than markup.');
  console.log('  Do NOT reach for --no-verify.\n');
  process.exit(1);
})().catch((err) => {
  console.error('\nverify:a11y FAILED: ' + err.message + '\n');
  process.exit(1);
});
