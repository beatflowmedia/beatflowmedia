#!/usr/bin/env node
//
// scripts/verify-radio-links.js
//
//   npm run verify:radio-links            # report which albums have a station page
//   npm run verify:radio-links -- --write # regenerate src/data/radioAlbums.js
//
// WHICH BFMG ALBUMS HAVE A PAGE ON THE STATION.
//
// WHY THIS IS NOT A slugify() CALL IN A COMPONENT
//
// BeatFlow Radio gives each album it AIRS a page at /music/<slug>, and radio/albums.js
// is explicit that this is selective: "an album in the catalogue that never airs gets no
// page". So the station has pages for some BFMG albums and deliberately not others --
// /music/unseen and /music/soft-love return 200, /music/eternal-flame returns 404.
//
// Deriving the slug in a component and rendering a link would therefore produce dead
// links to another property, which is worse than no link: it costs the reader a click
// and the site a little credibility, and BFMG's own npm run verify:links cannot see it
// because the URL is off-site.
//
// So the set is RESOLVED HERE, written to src/data/radioAlbums.js, and the component
// renders a link only for albums known to have one. The file is generated and
// reviewable in a pull request; re-run this when the station adds albums.
//
// WHY LINK AT ALL -- the reason is in radio/albums.js and it is the best sentence either
// repository has on the subject:
//
//   "Two sites saying the same thing compete for the same searches; two sites with
//    different jobs that link to each other do not."
//
// The station's album page is about HEARING the record -- which programmes play it, when,
// listen live -- and refuses to restate price or terms. BFMG's is about LICENSING it.
// Different jobs. The station already links here (radio/albums.js licenceLink()); nothing
// came back, which is half a mesh.

const fs = require('fs');
const path = require('path');
const https = require('https');

const { loadEnv, initAdmin, assertProject, args } = require('./lib/admin');

const STATION = 'https://beatflowradio.com';
const OUT = path.join(__dirname, '..', 'src', 'data', 'radioAlbums.js');

/**
 * The station's slug rule, COPIED EXACTLY from radio/station.js slugify().
 *
 * The first version of this added `.replace(/&/g, 'and')`, which seemed obviously right
 * and is not what the station does: it collapses any non-alphanumeric run to a dash, so
 * "Maps & Moments" is maps-moments, not maps-and-moments. That one extra line reported
 * an album as having no station page when it has one -- an instrument reading LOW, which
 * looks exactly like a clean result.
 *
 * Found by checking the number against the station's own source rather than trusting the
 * script's output. Which is the caveat added to the global CLAUDE.md the same morning.
 */
const slugify = (s) => String(s || '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '');

function head(url) {
  return new Promise((resolve) => {
    const req = https.request(url, { method: 'HEAD', timeout: 15000 }, (res) =>
      resolve(res.statusCode));
    req.on('timeout', () => { req.destroy(); resolve(0); });
    req.on('error', () => resolve(0));
    req.end();
  });
}

(async () => {
  loadEnv();
  const flags = args();
  const { admin, projectId } = initAdmin();
  assertProject(projectId, 'beatflowmedia');
  const db = admin.firestore();

  console.log('\nverify:radio-links — which BFMG albums have a page on the station?\n');

  const albums = await db.collection('albums').get();
  const found = {};
  let live = 0;

  for (const doc of albums.docs) {
    const title = doc.data().title || '';
    const slug = slugify(title);
    if (!slug) continue;
    const status = await head(`${STATION}/music/${slug}`);
    if (status === 200) {
      found[doc.id] = { slug, title };
      live += 1;
      console.log('  on air   %s  /music/%s', title.slice(0, 30).padEnd(30), slug);
    } else {
      console.log('  no page  %s  (%s)', title.slice(0, 30).padEnd(30), status || 'unreachable');
    }
  }

  console.log('');
  console.log('  %d of %d albums have a station page.', live, albums.size);
  console.log('  The station is selective on purpose — an album that never airs gets none.\n');

  if (!flags.has('--write')) {
    console.log('  Re-run with -- --write to regenerate src/data/radioAlbums.js\n');
    process.exit(0);
  }

  const body = `// src/data/radioAlbums.js
//
// GENERATED by scripts/verify-radio-links.js. Do not edit by hand.
//
// Which BFMG albums have a page on BeatFlow Radio, RESOLVED rather than derived. The
// station only gives a page to albums it airs, so a slug built in a component would
// produce dead off-site links that npm run verify:links cannot see.
//
// Regenerate: npm run verify:radio-links -- --write
//
// Last resolved: ${new Date().toISOString().slice(0, 10)}  (${live} of ${albums.size} albums)

const RADIO_ALBUMS = ${JSON.stringify(found, null, 2)};

const RADIO_BASE = '${STATION}';

/** The station page for a BFMG album id, or null when it does not air there. */
function radioUrlFor(albumId) {
  const hit = RADIO_ALBUMS[albumId];
  return hit ? \`\${RADIO_BASE}/music/\${hit.slug}\` : null;
}

module.exports = { RADIO_ALBUMS, RADIO_BASE, radioUrlFor };
`;

  fs.writeFileSync(OUT, body, 'utf8');
  console.log('  wrote src/data/radioAlbums.js\n');
  process.exit(0);
})().catch((err) => {
  console.error('\nverify:radio-links FAILED:', err.message, '\n');
  process.exit(1);
});
